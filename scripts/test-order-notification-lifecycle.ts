import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const source=(path:string)=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const api=source("src/app/api/admin/notifications/route.ts");
const store=source("src/shared/store/orders.ts");
const ctx=source("src/shared/components/shared/admin-notifications-context.tsx");
const bell=source("src/shared/components/shared/admin-notification-bell.tsx");
const table=source("src/shared/components/shared/orders-table.tsx");
assert.match(api,/status:OrderStatus.NEW/,"Only NEW orders count as pending action.");
assert.match(api,/prisma.order.count\(\{where:\{status:OrderStatus.NEW\}\}\)/);
assert.match(api,/counts.orders\+=newOrderCount/);
assert.match(api,/kind:\{not:"new_order"\}/,"Old order notification entries must not inflate read-based counts.");
assert.match(api,/id:`new-order:\$\{order.id\}`/,"Unseen order ID should be synthetic so it cannot be manually acknowledged.");
assert.match(ctx,/item.kind!=="new_order"/,"Opening a notification must never mark new orders as handled.");
assert.match(ctx,/ids:acknowledgeIds/);
assert.match(ctx,/europerfume:order-status-changed/,"Badge should refresh after status update.");
assert.match(store,/dispatchEvent\(new Event\("europerfume:order-status-changed"\)\)/);
assert.match(table,/value=\{OrderStatus.PENDING\}/,"In processing must use PENDING status.");
assert.match(bell,/Новый заказ исчезнет из счётчика после статуса/);
console.log("New-order notification lifecycle: NEW visible on open; PENDING removes; other alerts read-on-open; immediate refresh PASS");
