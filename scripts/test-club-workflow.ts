import assert from "node:assert/strict";
import {couponPolicyFailure,accountOrderEligible,loyaltyAwardAllowed,earnablePoints} from "../src/shared/lib/europerfume-club";
import {pointRedemptionQuote,earnedPointsAfterRefund,refundableSpentPoints} from "../src/shared/lib/loyalty-arithmetic";
import {readPricing} from "../src/shared/lib/tax";
// Full deterministic test of business rules; no production users/orders/email are modified.
const verifiedAt=new Date("2026-11-21T10:00:00Z");
const placedAt=new Date("2026-11-22T10:00:00Z");
const policy={kind:"WELCOME",active:true,startsAt:null,endsAt:null,validDaysAfterVerification:60,perUserLimit:1,globalLimit:null,usedCount:0,epoch:1};
const account={now:placedAt,userId:123,verifiedAt,priorUses:0,accountOrderCount:0};
assert.equal(couponPolicyFailure(policy,account),null);
assert.equal(couponPolicyFailure(policy,{...account,userId:null}),"ACCOUNT_REQUIRED");
assert.equal(couponPolicyFailure(policy,{...account,verifiedAt:null}),"EMAIL_UNVERIFIED");
assert.equal(couponPolicyFailure(policy,{...account,accountOrderCount:1}),"FIRST_ORDER_ONLY");
assert.equal(couponPolicyFailure(policy,{...account,priorUses:1}),"USED");
assert.equal(accountOrderEligible(123,verifiedAt,placedAt),true);
assert.equal(accountOrderEligible(null,verifiedAt,placedAt),false);
const firstOrder=readPricing({version:1,country:"DEU",capturedAt:placedAt.toISOString(),policy:{mode:"exempt",rateBasisPoints:0},subtotalGrossCents:10000,shippingGrossCents:0,discountGrossCents:1000,totalGrossCents:9000,lines:[{productId:1,variationId:null,title:"Duft",quantity:1,onTap:false,grossCents:10000}]});
assert.ok(firstOrder);
const earned=earnablePoints(firstOrder.lines,firstOrder.discountGrossCents);
assert.equal(earned,450);
assert.equal(loyaltyAwardAllowed(placedAt,null,null),false);
assert.equal(loyaltyAwardAllowed(placedAt,placedAt,null),true);
assert.equal(loyaltyAwardAllowed(placedAt,placedAt,placedAt),false);
const second=pointRedemptionQuote({balancePoints:earned,eligibleAfterCouponCents:10000});
assert.deepEqual(second,{spendPoints:450,discountCents:450});
assert.equal(pointRedemptionQuote({balancePoints:2000,eligibleAfterCouponCents:10000}).spendPoints,2000);
const partial=earnedPointsAfterRefund({originalEarnedPoints:earned,originalEligibleCents:9000,cumulativeEligibleRefundCents:3600});
assert.deepEqual(partial,{remainingEarnedPoints:270,reversalPoints:180});
assert.deepEqual(earnedPointsAfterRefund({originalEarnedPoints:earned,originalEligibleCents:9000,cumulativeEligibleRefundCents:3600}),partial,"same refund quote must be deterministic");
assert.equal(refundableSpentPoints({originalSpentPoints:second.spendPoints,originalEligibleChargedCents:10000,cumulativeEligibleRefundCents:5000}),225);
assert.equal(refundableSpentPoints({originalSpentPoints:second.spendPoints,originalEligibleChargedCents:10000,cumulativeEligibleRefundCents:10000}),450);
assert.throws(()=>earnedPointsAfterRefund({originalEarnedPoints:earned,originalEligibleCents:9000,cumulativeEligibleRefundCents:9001}),/REFUND_EXCEEDS_PURCHASE/);
console.log("Simulated registration > WELCOME10 > paid/handed-over > award > spend > partial/full refund: PASS (pure rules only).");
