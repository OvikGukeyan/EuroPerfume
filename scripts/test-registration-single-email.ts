import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {registrationSchema} from "../src/shared/lib/registration-consent";
const read=(p:string)=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const actions=read("src/app/actions.ts");
const verify=read("src/app/api/auth/verify/route.ts");
const renew=read("src/app/api/auth/renew-verification/route.ts");
const resend=read("src/app/api/auth/resend-verification/route.ts");
const mail=read("src/shared/components/shared/email-templates/user-verification.tsx");
const ui=read("src/shared/components/shared/modals/auth-modal/forms/register-form.tsx");
const status=read("src/app/[locale]/(root)/verify/page.tsx");
const newsletter=read("src/app/api/newsletter/route.ts");
const newsletterPage=read("src/app/[locale]/(root)/newsletter/page.tsx");
for(const locale of ["de","ru"]){
 const base={fullName:"Test Customer",email:"test@example.com",password:"secure-password-123",confirmPassword:"secure-password-123",acceptPolicy:true,locale};
 assert.equal(registrationSchema(locale).parse(base).marketingOptIn,false);
 assert.equal(registrationSchema(locale).parse({...base,marketingOptIn:true}).marketingOptIn,true);
}
const registration=actions.slice(actions.indexOf("export async function registerUser("),actions.indexOf("export async function resetPassword"));
assert.match(registration,/const code = "v2_" \+ randomBytes\(32\)/);
assert.match(registration,/UserVerificationTemplate\(\{code,locale:body.locale,marketingOptIn:body.marketingOptIn\}\)/);
assert.doesNotMatch(registration,/sendNewsletterConfirmation\(/);
assert.match(verify,/if\(existing.code.startsWith\("v2_"\)\)/);
assert.match(verify,/confirmationSentAt:null/);
assert.match(verify,/record.user.verified\)return result\("already"\)/);
assert.doesNotMatch(verify,/verificationCode.delete\(/);
assert.match(verify,/sendWelcomeOfferIfConsented/);
assert.match(verify,/result\("expired",true\)/);
assert.match(renew,/existing.code.startsWith\("v2_"\)/);
assert.match(renew,/15\*60\*1000/);
assert.match(resend,/old\?\.code.startsWith\("v2_"\)/);
assert.match(mail,/marketingOptIn\?/);
assert.match(ui,/Одно письмо подтверждает и аккаунт/);
assert.doesNotMatch(ui,/мы отправили второе письмо/);
assert.match(status,/\/api\/auth\/renew-verification/);
assert.match(newsletter,/result='expired'/);
assert.match(newsletter,/result='already'/);
assert.match(newsletterPage,/\/api\/newsletter\/renew/);
console.log("One-email verification: opt-in consent, versioned old/new link isolation, idempotency, expiry renewal and UI PASS (static/pure).");
